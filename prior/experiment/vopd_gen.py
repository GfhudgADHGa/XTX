#!/usr/bin/env python3
"""Generates vopd_bench.hip.cpp. Every snippet is validated with the gfx1100 assembler before it is emitted.
Register plan (explicit, so VOPD bank / parity rules are under our control):
  slot j: X dst v(2j) (even)   Y dst v(2j+1) (odd)       -- up to 6 slots => v0..v11
  X src0 v16 (bank0)  X vsrc1 v20 (bank0)  Y src0 v19 (bank3)  Y vsrc1 v21 (bank1) / own acc for int/mul chains
"""
import subprocess, sys
MAXSLOT = 6
def X(j):  return 2*j
def Y(j):  return 2*j+1
V = {
 # name: (fn(j)-> asm text, instructions per slot, description)
 'SEP_FF':  (lambda j: f"v_fmac_f32 v{X(j)}, v16, v20\n v_fmac_f32 v{Y(j)}, v19, v21\n", 2, 'fmac + fmac, two VOP2 instrs'),
 'DUAL_FF': (lambda j: f"v_dual_fmac_f32 v{X(j)}, v16, v20 :: v_dual_fmac_f32 v{Y(j)}, v19, v21\n", 1, 'fmac + fmac, one VOPD'),
 'SEP_FM':  (lambda j: f"v_fmac_f32 v{X(j)}, v16, v20\n v_mul_f32 v{Y(j)}, v19, v{Y(j)}\n", 2, 'fmac + mul, two instrs'),
 'DUAL_FM': (lambda j: f"v_dual_fmac_f32 v{X(j)}, v16, v20 :: v_dual_mul_f32 v{Y(j)}, v19, v{Y(j)}\n", 1, 'fmac + mul, one VOPD'),
 'SEP_FI':  (lambda j: f"v_fmac_f32 v{X(j)}, v16, v20\n v_add_nc_u32 v{Y(j)}, v19, v{Y(j)}\n", 2, 'FP fmac + INT add, two instrs'),
 'DUAL_FI': (lambda j: f"v_dual_fmac_f32 v{X(j)}, v16, v20 :: v_dual_add_nc_u32 v{Y(j)}, v19, v{Y(j)}\n", 1, 'FP fmac + INT add, one VOPD'),
 'SEP_FL':  (lambda j: f"v_fmac_f32 v{X(j)}, v16, v20\n v_lshlrev_b32 v{Y(j)}, v19, v{Y(j)}\n", 2, 'FP fmac + INT shift, two instrs'),
 'DUAL_FL': (lambda j: f"v_dual_fmac_f32 v{X(j)}, v16, v20 :: v_dual_lshlrev_b32 v{Y(j)}, v19, v{Y(j)}\n", 1, 'FP fmac + INT shift, one VOPD'),
 'SEP_DOT': (lambda j: f"v_dot2acc_f32_f16 v{X(j)}, v16, v20\n v_fmac_f32 v{Y(j)}, v19, v21\n", 2, 'dot2acc_f16 + fmac, two instrs'),
 'DUAL_DOT':(lambda j: f"v_dual_dot2acc_f32_f16 v{X(j)}, v16, v20 :: v_dual_fmac_f32 v{Y(j)}, v19, v21\n", 1, 'dot2acc_f16 + fmac, one VOPD'),
}
def assembles(text):
    p = subprocess.run(['clang','-target','amdgcn-amd-amdhsa','-mcpu=gfx1100','-x','assembler','-c','-o','/dev/null','-'],
                       input=text, capture_output=True, text=True)
    return p.returncode == 0, p.stderr.strip().splitlines()[:1]
for n,(fn,_,_) in V.items():
    ok, err = assembles("".join(fn(j) for j in range(MAXSLOT)))
    if not ok: sys.exit(f"{n}: does not assemble: {err}")
ILPS = [1, 2, 4, 6]
init = "".join(f"v_mov_b32 v{i}, {hex(0x3f800000 + 0x1000*i)}\\n" for i in range(24))
join = "".join(f"v_readfirstlane_b32 %0, v{i}\\n" for i in range(2*MAXSLOT))
clob = ", ".join(f'"v{i}"' for i in range(24))
out = ['''// GENERATED by vopd_gen.py -- do not edit by hand.
// VOPD (gfx11 dual-issue) vs. the same two operations as separate instructions, single wave32.
#include <hip/hip_runtime.h>
#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#define HIP_CHECK(x) do { hipError_t e = (x); if (e != hipSuccess) { fprintf(stderr, "%s:%d %s\\n", __FILE__, __LINE__, hipGetErrorString(e)); exit(1);} } while (0)
''']
out.append(f'#define INIT_ASM "{init}"\n#define JOIN_ASM "{join}"\n#define CLOBBERS {clob}\n')
out.append('''#define DEF_KERNEL(NAME, ASMSTR)                                                                           \\
  template <int K> __global__ __launch_bounds__(32) void NAME(uint32_t* out, int L) {                      \\
    uint32_t t0 = 0, t1 = 0, sink = 0;                                                                      \\
    asm volatile(INIT_ASM ::: CLOBBERS);                                                                    \\
    _Pragma("nounroll") for (int pass = 0; pass < 2; pass++) {                                              \\
      int Lp = pass ? L : 1;                                                                                \\
      if (pass) asm volatile("s_getreg_b32 %0, hwreg(HW_REG_SHADER_CYCLES)" : "=s"(t0));                    \\
      _Pragma("nounroll") for (int it = 0; it < Lp; it++) {                                                 \\
        _Pragma("unroll") for (int k = 0; k < K; k++) asm volatile(ASMSTR ::: CLOBBERS);                    \\
      }                                                                                                     \\
      asm volatile(JOIN_ASM : "=s"(sink) :: CLOBBERS);                                                      \\
      if (pass) asm volatile("s_getreg_b32 %0, hwreg(HW_REG_SHADER_CYCLES)" : "=s"(t1));                    \\
    }                                                                                                       \\
    if (threadIdx.x == 0) { out[0] = (t1 - t0) & 0xFFFFF; out[1] = sink; }                                  \\
  }
''')
for n,(fn,_,_) in V.items():
    for ilp in ILPS:
        text = "".join(fn(j) for j in range(ilp)).replace("\n", "\\n")
        out.append(f'DEF_KERNEL({n}_{ilp}, "{text}")\n')
out.append('''
template <int K, class F> uint32_t timeit(F kernel, uint32_t* d, int L) {
  uint32_t best = 0xFFFFFFFF;
  for (int rep = 0; rep < 9; rep++) {
    hipLaunchKernelGGL(kernel, dim3(1), dim3(32), 0, 0, d, L);
    HIP_CHECK(hipDeviceSynchronize());
    uint32_t h[2]; HIP_CHECK(hipMemcpy(h, d, sizeof h, hipMemcpyDeviceToHost));
    best = std::min(best, h[0]);
  }
  return best;
}
__global__ void ramp(float* p, int iters) { float a = threadIdx.x * 1e-3f, b = 1.0001f; for (int i = 0; i < iters; i++) a = fmaf(a, b, 0.5f); if (a == 12345.f) p[0] = a; }

#define ROW(NAME, ILP, INSTR, DESC) do {                                                                    \\
    const int L = 32, K1 = 16, K2 = 48;                                                                      \\
    uint32_t lo = timeit<K1>(NAME##_##ILP<K1>, d, L), hi = timeit<K2>(NAME##_##ILP<K2>, d, L);              \\
    double step = (double(hi) - lo) / (double(L) * (K2 - K1));                                               \\
    printf("%-9s ILP=%d  %-34s  cyc/step=%7.3f  cyc/slot=%6.3f  cyc/instr=%6.3f  arith-ops/cyc=%5.2f\\n",      \\
           #NAME, ILP, DESC, step, step / ILP, step / (ILP * INSTR), 2.0 * ILP / step);                      \\
  } while (0)

int main() {
  hipDeviceProp_t p; HIP_CHECK(hipGetDeviceProperties(&p, 0));
  printf("device: %s  arch=%s\\n", p.name, p.gcnArchName);
  uint32_t* d; HIP_CHECK(hipMalloc(&d, 16));
  float* r; HIP_CHECK(hipMalloc(&r, 64));
  hipLaunchKernelGGL(ramp, dim3(4096), dim3(256), 0, 0, r, 1 << 22); HIP_CHECK(hipDeviceSynchronize());
''')
for n,(fn,instr,desc) in V.items():
    for ilp in ILPS:
        out.append(f'  ROW({n}, {ilp}, {instr}, "{desc}");\n')
    out.append('  puts("");\n')
out.append("  return 0;\n}\n")
open('vopd_bench.hip.cpp','w').write("".join(out))
print("generated vopd_bench.hip.cpp;", len(V), "variants x", len(ILPS), "ILPs; all snippets assemble")
