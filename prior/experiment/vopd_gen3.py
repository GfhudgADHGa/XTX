#!/usr/bin/env python3
"""Generates vopd_banks_full.hip.cpp: does the VOPD register *bank* assignment change throughput?
Sweeps all 24 assignments of {X.src0, X.vsrc1, Y.src0, Y.vsrc1} -> banks {0,1,2,3} (physical reg = 16+bank),
plus a variant where every slot uses distinct physical source registers.  6 slots, FP+FP dual fmac."""
import itertools, subprocess, sys
S = 6
def asm_for(x0, x1, y0, y1, per_slot=False):
    lines = []
    for j in range(S):
        off = 4*j if per_slot else 0
        lines.append(f"v_dual_fmac_f32 v{2*j}, v{x0+off}, v{x1+off} :: v_dual_fmac_f32 v{2*j+1}, v{y0+off}, v{y1+off}")
    return "\\n".join(lines) + "\\n"
def ok(text):
    return subprocess.run(['clang','-target','amdgcn-amd-amdhsa','-mcpu=gfx1100','-x','assembler','-c','-o','/dev/null','-'],
                          input=text.replace("\\n","\n"), capture_output=True, text=True).returncode == 0
cases = []
for perm in itertools.product(range(4), repeat=4):
    r = tuple(16+b for b in perm)
    t = asm_for(*r)
    cases.append((f"X0b{perm[0]} X1b{perm[1]} Y0b{perm[2]} Y1b{perm[3]}", t, ok(t)))
# distinct physical registers per slot (skipped in the full sweep) (banks follow the best-guess pattern X0=b0 X1=b1 Y0=b2 Y1=b3)

legal = [(n,t) for n,t,o in cases if o]
print(f"{len(legal)} of {len(cases)} bank assignments are legal VOPD", file=sys.stderr)
init = "".join(f"v_mov_b32 v{i}, {hex(0x3f800000 + 0x1000*i)}\\n" for i in range(48))
join = "".join(f"v_readfirstlane_b32 %0, v{i}\\n" for i in range(2*S))
clob = ", ".join(f'"v{i}"' for i in range(48))
o = ['''// GENERATED by vopd_gen2.py
#include <hip/hip_runtime.h>
#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#define HIP_CHECK(x) do { hipError_t e = (x); if (e != hipSuccess) { fprintf(stderr, "%s:%d %s\\n", __FILE__, __LINE__, hipGetErrorString(e)); exit(1);} } while (0)
''']
o.append(f'#define INIT_ASM "{init}"\n#define JOIN_ASM "{join}"\n#define CLOBBERS {clob}\n')
o.append('''#define DEF_KERNEL(NAME, ASMSTR)                                                                           \\
  template <int K> __global__ __launch_bounds__(32) void NAME(uint32_t* out, int L) {                      \\
    uint32_t t0 = 0, t1 = 0, sink = 0;                                                                      \\
    asm volatile(INIT_ASM ::: CLOBBERS);                                                                    \\
    _Pragma("nounroll") for (int pass = 0; pass < 2; pass++) {                                              \\
      int Lp = pass ? L : 1;                                                                                \\
      if (pass) asm volatile("s_getreg_b32 %0, hwreg(HW_REG_SHADER_CYCLES)" : "=s"(t0));                    \\
      _Pragma("nounroll") for (int it = 0; it < Lp; it++) {                                                 \\
        _Pragma("unroll") for (int k = 0; k < K; k++) asm volatile(ASMSTR ::: CLOBBERS);                    \\
      }                                                                                                     \\
      asm volatile(JOIN_ASM : "=s"(sink) :: CLOBBERS);                                                      \\
      if (pass) asm volatile("s_getreg_b32 %0, hwreg(HW_REG_SHADER_CYCLES)" : "=s"(t1));                    \\
    }                                                                                                       \\
    if (threadIdx.x == 0) { out[0] = (t1 - t0) & 0xFFFFF; out[1] = sink; }                                  \\
  }
''')
for i,(n,t) in enumerate(legal): o.append(f'DEF_KERNEL(B{i}, "{t}")\n')
o.append('''template <class F> uint32_t timeit(F k, uint32_t* d, int L) { uint32_t best = 0xFFFFFFFF;
  for (int rep = 0; rep < 9; rep++) { hipLaunchKernelGGL(k, dim3(1), dim3(32), 0, 0, d, L); HIP_CHECK(hipDeviceSynchronize());
    uint32_t h[2]; HIP_CHECK(hipMemcpy(h, d, sizeof h, hipMemcpyDeviceToHost)); best = std::min(best, h[0]); } return best; }
__global__ void ramp(float* p, int iters) { float a = threadIdx.x * 1e-3f, b = 1.0001f; for (int i = 0; i < iters; i++) a = fmaf(a, b, 0.5f); if (a == 12345.f) p[0] = a; }
#define ROW(I, NAME) do { const int L = 32, K1 = 8, K2 = 40; \\
    uint32_t lo = timeit(B##I<K1>, d, L), hi = timeit(B##I<K2>, d, L); double step = (double(hi) - lo) / (double(L) * (K2 - K1)); \\
    printf("%-40s cyc/VOPD=%6.3f  arith-ops/cyc=%5.2f\\n", NAME, step / 6.0, 12.0 / step); } while (0)
int main() { uint32_t* d; HIP_CHECK(hipMalloc(&d, 16)); float* r; HIP_CHECK(hipMalloc(&r, 64));
  hipLaunchKernelGGL(ramp, dim3(4096), dim3(256), 0, 0, r, 1 << 22); HIP_CHECK(hipDeviceSynchronize());
''')
for i,(n,t) in enumerate(legal): o.append(f'  ROW({i}, "{n}");\n')
o.append("  return 0;\n}\n")
open('vopd_banks_full.hip.cpp','w').write("".join(o))
